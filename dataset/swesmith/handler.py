def _compute_fix_patch(from_code: str, to_code: str, file_path: str) -> str:
    """Unified diff (git-apply compatible) turning from_code into to_code."""
    from_lines = from_code.splitlines(keepends=True)
    to_lines = to_code.splitlines(keepends=True)
    if from_lines and not from_lines[-1].endswith("\n"):
        from_lines[-1] += "\n"
    if to_lines and not to_lines[-1].endswith("\n"):
        to_lines[-1] += "\n"
    return "".join(difflib.unified_diff(
        from_lines, to_lines,
        fromfile=f"a/{file_path}", tofile=f"b/{file_path}",
    ))


def _new_file_patch(file_path: str, content: str) -> str:
    """Unified diff that creates file_path with the given content."""
    lines = content.splitlines(keepends=True)
    if lines and not lines[-1].endswith("\n"):
        lines[-1] += "\n"
    body = "".join("+" + l for l in lines)
    return (f"diff --git a/{file_path} b/{file_path}\nnew file mode 100644\n"
            f"--- /dev/null\n+++ b/{file_path}\n@@ -0,0 +1,{len(lines)} @@\n{body}")


def _validation_id(task_id: str, patch: str) -> str:
    """
    Instance id used for Docker container names and log folders.

    NOTE: [design thought] The patch hash makes concurrent runs (several models
    evaluated in parallel, or two bugs that share a task_id) use distinct
    containers/log folders instead of clobbering each other, and lets identical
    patches reuse each other's logs. swesmith asserts that
    ``instance_id.rsplit(".", 1)[0] == repo_name``, so the suffix must not
    contain a dot.
    """
    return f"{task_id}__{hashlib.sha1(patch.encode()).hexdigest()[:10]}"


def _selected_test_paths(eval_script: Path) -> list[str]:
    """Test paths passed to pytest in a swesmith eval.sh ([] = whole suite)."""
    if not eval_script.exists():
        return []
    for line in reversed(eval_script.read_text(errors="replace").splitlines()):
        tokens = line.replace(";", " ").split()
        if "pytest" in tokens:
            args = tokens[tokens.index("pytest") + 1:]
            return [a.rstrip("/") for a in args if not a.startswith("-")]
    return []


def _syntax_ok(code: str) -> bool:
    try:
        ast.parse(code)
        return True
    except (SyntaxError, ValueError):
        return False


def _set_arch(repos, registry) -> None:
    """Force x86_64 on all repos — Docker Hub only has x86_64 images."""
    for repo in repos:
        try:
            registry.get(repo).arch = "x86_64"
        except Exception:
            pass


def _run_pregold(repos, registry, run_patch_in_container,
                 KEY_INSTANCE_ID, REF_SUFFIX, LOG_DIR_RUN_VALIDATION, close_logger) -> None:
    """Run the clean baseline once per repo; results are cached to disk."""
    for repo in repos:
        try:
            rp = registry.get(repo)
            ref_inst = f"{rp.repo_name}{REF_SUFFIX}"
            ref_dir = LOG_DIR_RUN_VALIDATION / repo / ref_inst
            if rp.min_pregold or ref_dir.exists():
                continue
            (LOG_DIR_RUN_VALIDATION / repo).mkdir(parents=True, exist_ok=True)
            print(f"[SWESmithHandler] Running pre-gold baseline for {repo}...")
            logger, timed_out = run_patch_in_container(
                {KEY_INSTANCE_ID: ref_inst}, repo,
                LOG_DIR_RUN_VALIDATION, rp.timeout_ref,
            )
            close_logger(logger)
            if timed_out:
                print(f"[SWESmithHandler] Pre-gold timed out for {repo}, skipping.")
        except Exception as e:
            print(f"[SWESmithHandler] Pre-gold failed for {repo}: {e}")


def _import_swesmith():
    try:
        from swesmith.harness.valid import run_validation
        from swesmith.harness.utils import run_patch_in_container
        from swesmith.constants import (KEY_PATCH, REF_SUFFIX, LOG_DIR_RUN_VALIDATION,
                                        LOG_TEST_OUTPUT_PRE_GOLD)
        from swesmith.profiles import registry
        from swebench.harness.constants import KEY_INSTANCE_ID, LOG_REPORT, LOG_TEST_OUTPUT
        from swebench.harness.docker_build import close_logger
    except ImportError as e:
        raise ImportError(f"swesmith/swebench not importable: {e}\n{_INSTALL_MSG}") from e
    return dict(run_validation=run_validation, run_patch_in_container=run_patch_in_container,
                KEY_PATCH=KEY_PATCH, REF_SUFFIX=REF_SUFFIX, LOG_DIR=LOG_DIR_RUN_VALIDATION,
                LOG_TEST_OUTPUT_PRE_GOLD=LOG_TEST_OUTPUT_PRE_GOLD, registry=registry,
                KEY_INSTANCE_ID=KEY_INSTANCE_ID, LOG_REPORT=LOG_REPORT,
                LOG_TEST_OUTPUT=LOG_TEST_OUTPUT, close_logger=close_logger)


class SWESmithHandler(DatasetHandler):
    """DatasetHandler for SWE-smith repository files. See module docstring for modes."""

    install_subdir = "install"
    # Code moves show up in file_diff as Add(N) next to Delete/Modify(N-1); treat
    # them as one block (see utils.parse_diff_to_blocks).
    merge_adjacent_add_blocks = True

    def __init__(self, data_file: str | Path | None = None, n_workers: int = 4):
        self._data_file = Path(data_file) if data_file else None
        self._data_index: dict[str, dict] | None = None
        self._index_lock = threading.Lock()
        self.n_workers = n_workers

    # ── metadata index ────────────────────────────────────────────────────────

    @property
    def data_index(self) -> dict[str, dict]:
        """Lazily-built task_id -> entry index (loading SWE-smith data is opt-in)."""
        if self._data_index is None:
            self._data_index = {}
            if self._data_file is not None:
                if self._data_file.exists():
                    self.register(json.load(open(self._data_file)))
                    print(f"[SWESmithHandler] loaded {len(self._data_index)} instances "
                          f"from {self._data_file}")
                else:
                    print(f"[SWESmithHandler] WARNING: data file not found at {self._data_file}")
        return self._data_index

    def register(self, data: list[dict]) -> None:
        """Add entries that carry task metadata (gt_solution + repo) to the index."""
        index = self.data_index
        with self._index_lock:
            for item in data:
                if item.get("gt_solution") and item.get("repo") and "__atom__" not in item.get("task_id", ""):
                    index[item["task_id"]] = item

    def _lookup(self, task_id: str) -> dict:
        """
        Index entry for task_id or for the task it was derived from.

        NOTE: [edge case callout] verification entries often carry derived ids:
        atomicity probes ("<id>__atom__<k>_<lines>") in bug generation, and the
        Evaluator's semantic-equivalence ("<id>_<n>") and redundancy
        ("<id>_<n>_<tol>_<k>") probes. Like BigCodeBenchHandler.save_formatted_gt,
        strip "_<suffix>" parts until a known task id is found.
        """
        index = self.data_index
        key = task_id.split("__atom__")[0]
        while key not in index and "_" in key:
            key = key.rsplit("_", 1)[0]
        return index.get(key, {})

    def _meta(self, task_id: str, item: dict) -> dict:
        """Metadata for task_id (see _lookup); fields set on item take precedence."""
        meta = self._lookup(task_id)
        return {k: item.get(k) or meta.get(k) for k in
                ("gt_solution", "repo", "image_name", "target_file",
                 "augmented_tests", "augmented_test_ids", "augmented_test_setup")}

    # ── DatasetHandler interface ──────────────────────────────────────────────

    def mark_editable_lines(self, data):
        """Mark editable/deletable lines; frozen_lines=0 (no starter-code prefix)."""
        if not data:
            return
        for d in data:
            code_lines = d["gt_solution"].splitlines()
            d["frozen_lines"] = 0
            d["gt_length"] = len(code_lines)
            d["editable_lines"] = []
            d["deletable_lines"] = []

            for i, line in enumerate(code_lines):
                if not line.strip():
                    continue
                stripped = line.strip()
                editable = not any(kw in stripped for kw in self.NO_CHANGE_KEYWORDS)
                deletable = editable and not any(kw in stripped for kw in self.NO_DELETE_KEYWORDS)

                if editable and deletable:
                    if stripped.endswith(":"):
                        deletable = False
                    elif i > 0 and code_lines[i - 1].strip().endswith(":"):
                        if i == len(code_lines) - 1:
                            deletable = False
                        else:
                            prev_indent = get_indentation(code_lines[i - 1])
                            next_indent = get_indentation(code_lines[i + 1])
                            if prev_indent == next_indent:
                                deletable = False
                    elif (0 < i < len(code_lines) - 1
                          and not code_lines[i - 1].strip()
                          and not code_lines[i + 1].strip()):
                        deletable = False

                if editable:
                    d["editable_lines"].append((i + 1, line))
                if editable and deletable:
                    d["deletable_lines"].append((i + 1, line))

    def preprocess(self, raw_data: list[dict]) -> list[dict]:
        """Pass-through with format validation; expects 'buggy_code' or 'gt_solution'."""
        if not raw_data:
            return raw_data
        if "buggy_code" not in raw_data[0] and "gt_solution" not in raw_data[0]:
            raise ValueError(
                "SWESmithHandler.preprocess() expects 'buggy_code' (fix-eval) "
                "or 'gt_solution' (bug-gen). Got neither — check your input file."
            )
        return raw_data

    def save_formatted_gt(self, log_file_prefix: str, data: list[dict]) -> str | None:
        """Register task metadata for verification and write it to a GT JSONL log."""
        self.register(data)
        rows = [item for item in data
                if item.get("gt_solution") and "__atom__" not in item.get("task_id", "")]
        if not rows:
            return None
        gt_file = f"{log_file_prefix}.jsonl"
        Path(gt_file).parent.mkdir(parents=True, exist_ok=True)
        with open(gt_file, "w") as f:
            for item in rows:
                f.write(json.dumps({
                    "task_id": item["task_id"],
                    "repo": item.get("repo"),
                    "target_file": item.get("target_file", "solution.py"),
                    "gt_solution": item["gt_solution"],
                }) + "\n")
        return gt_file

    def build_verify_unit_test(self, log_file_prefix: str, results: list[dict],
                               sol_field: str = "solution") -> str | None:
        """Write the verify JSONL consumed by verify_unit_test()."""
        verify_file = f"{log_file_prefix}.jsonl"
        Path(verify_file).parent.mkdir(parents=True, exist_ok=True)
        mode = MODE_BUG_GEN if sol_field == "buggy_code" else MODE_FIX_EVAL
        written = 0
        with open(verify_file, "w") as f:
            for item in results:
                code = item.get(sol_field)
                if code is None:
                    continue
                task_id = item.get("task_id", "")
                f.write(json.dumps({"task_id": task_id, "mode": mode, "code": code,
                                    **self._meta(task_id, item)}) + "\n")
                written += 1
        if not written:
            print("No submissions to evaluate.")
        return verify_file if written else None

    def verify_unit_test(self, verify_file: str, gt_file: str | None = None,
                         timeout_per_task: int = 20, timeout: int = 3600,
                         n_workers: int | None = None):
        """
        Run Docker validation for every entry in verify_file.

        Returns (fail_ids, correct_ids, feedback) where feedback maps task_id to
        a failure string (fix-eval) or to {"FAIL_TO_PASS", "PASS_TO_PASS"} for
        detected bugs (bug-gen). An entry that could not be run (Docker error)
        is dropped in bug-gen mode and counted as a failure in fix-eval mode.
        """
        entries = [json.loads(l) for l in open(verify_file) if l.strip()]
        if not entries:
            return [], [], {}
        # The Evaluator writes the verify file before calling save_formatted_gt,
        # so metadata missing at build time is filled in from the index here.
        entries = [{**e, **{k: v for k, v in self._meta(e["task_id"], e).items() if v}}
                   for e in entries]
        workers = max(1, min(n_workers or self.n_workers, len(entries)))
        sw = _import_swesmith()
        repos = {e["repo"] for e in entries if e.get("repo")}
        _set_arch(repos, sw["registry"])
        _run_pregold(repos, sw["registry"], sw["run_patch_in_container"],
                     sw["KEY_INSTANCE_ID"], sw["REF_SUFFIX"], sw["LOG_DIR"], sw["close_logger"])

        mode = entries[0].get("mode", MODE_FIX_EVAL)
        if mode == MODE_BUG_GEN:
            judge, ckpt_file, desc = self._judge_bug, None, "SWE-smith bug validation"
        else:
            judge, desc = self._judge_fix, "SWE-smith fix-eval"
            ckpt_file = Path(str(verify_file) + ".ckpt.json")

        # NOTE: [design thought] fix-eval runs are long (one Docker test-suite run
        # per model output), so outcomes are checkpointed. The key includes a hash
        # of the code: the Evaluator reuses one verify-file name per model, and a
        # re-evaluation of different outputs must not pick up stale outcomes.
        # Docker errors ("drop") are not persisted so a resumed run retries them.
        def _key(e):
            return f"{e['task_id']}|{hashlib.sha1(e.get('code', '').encode()).hexdigest()[:12]}"

        ckpt = {}
        if ckpt_file is not None and ckpt_file.exists():
            try:
                ckpt = json.load(open(ckpt_file))
                print(f"[{desc}] resuming from checkpoint: {len(ckpt)}/{len(entries)} done")
            except Exception:
                ckpt = {}
        outcomes = {}
        lock = threading.Lock()

        def _record(key, outcome):
            with lock:
                outcomes[key] = outcome
                if ckpt_file is not None and outcome[0] != "drop":
                    ckpt[key] = outcome
                    json.dump(ckpt, open(ckpt_file, "w"))

        todo = [e for e in entries if _key(e) not in ckpt]
        print(f"[SWESmithHandler] {desc}: {len(todo)} entries, {workers} workers")
        with ThreadPoolExecutor(max_workers=workers) as pool:
            futures = {pool.submit(judge, e, sw): _key(e) for e in todo}
            for fut in tqdm.tqdm(as_completed(futures), total=len(futures), desc=desc):
                try:
                    outcome = fut.result()
                except Exception as e:  # Docker / harness failure
                    outcome = ("drop", f"{type(e).__name__}: {e}")
                _record(futures[fut], list(outcome))

        fail_ids, correct_ids, feedback = [], [], {}
        for e in entries:
            status, info = outcomes.get(_key(e)) or ckpt.get(_key(e)) or ("drop", "not run")
            if status == "fail":
                fail_ids.append(e["task_id"])
                if info:
                    feedback[e["task_id"]] = info
            elif status == "correct":
                correct_ids.append(e["task_id"])
            else:
                if mode == MODE_FIX_EVAL:
                    # An unrunnable fix is an incorrect fix.
                    fail_ids.append(e["task_id"])
                feedback[e["task_id"]] = info
        if ckpt_file is not None and ckpt_file.exists() and all(_key(e) in ckpt for e in entries):
            ckpt_file.unlink()
        return fail_ids, correct_ids, feedback

    # ── judging ───────────────────────────────────────────────────────────────

    def _run(self, entry: dict, code: str, sw: dict):
        """Apply gt->code to the repo and run its suite; return (status, val_id, patch)."""
        target_file = entry.get("target_file") or "solution.py"
        patch = _compute_fix_patch(entry["gt_solution"], code, target_file)
        if not patch:
            return "identical", None, patch
        val_id = _validation_id(entry["task_id"], patch)
        # The id embeds the patch hash, so an existing report for it is the
        # result of this exact patch (e.g. another model produced the same fix).
        report_path = sw["LOG_DIR"] / entry["repo"] / val_id / sw["LOG_REPORT"]
        if report_path.exists():
            try:
                report = json.loads(report_path.read_text())
                if "FAIL_TO_PASS" in report:
                    return ("1+_f2p" if report["FAIL_TO_PASS"] else "0_f2p"), val_id, patch
            except (json.JSONDecodeError, OSError):
                pass
        result = sw["run_validation"]({sw["KEY_INSTANCE_ID"]: val_id, "repo": entry["repo"],
                                       sw["KEY_PATCH"]: patch})
        return result.get("status", "fail"), val_id, patch

    def _broken_tests(self, repo: str, val_id: str, sw: dict) -> list[str] | None:
        """
        Tests that pass on the clean repo but do not pass after the patch.

        NOTE: [edge case callout] swesmith's report only compares tests present in
        BOTH runs, so a patch that breaks test collection (syntax/import error)
        makes the tests disappear and is reported as "0_f2p". Missing tests are
        failures here. Returns None when the logs are unavailable.
        """
        rp = sw["registry"].get(repo)
        folder = sw["LOG_DIR"] / repo
        patched_log = folder / val_id / sw["LOG_TEST_OUTPUT"]
        ref_log = (folder / val_id / sw["LOG_TEST_OUTPUT_PRE_GOLD"] if rp.min_pregold
                   else folder / f"{repo}{sw['REF_SUFFIX']}" / sw["LOG_TEST_OUTPUT"])
        if not patched_log.exists() or not ref_log.exists():
            return None
        patched = rp.log_parser(patched_log.read_text(errors="replace"))
        ref = rp.log_parser(ref_log.read_text(errors="replace"))
        selected = _selected_test_paths(folder / val_id / "eval.sh")
        if selected:
            # min_testing profiles run only the test files related to the edited
            # source file; compare against the reference run on those files only.
            ref = {t: s for t, s in ref.items()
                   if any(t == p or t.startswith(p + "::") or t.startswith(p + "/") for p in selected)}
        return sorted(t for t, s in ref.items() if s in _PASSING and patched.get(t) not in _PASSING)

    def _augmented_failures(self, entry: dict, code: str, sw: dict) -> list[str]:
        """Augmented tests (from test_adequacy.py) that fail on code; [] if none exist."""
        test_ids = entry.get("augmented_test_ids") or []
        if not test_ids:
            return []
        results = self.run_tests_in_container(
            entry["repo"], {entry["target_file"]: code, **(entry.get("augmented_tests") or {})},
            test_ids, sw=sw, extra_setup=entry.get("augmented_test_setup") or "")
        return [t for t in test_ids if results.get(t) not in _PASSING]

    def _judge_bug(self, entry: dict, sw: dict):
        """bug-gen: ("fail", f2p) if the bug is detected, ("correct", None) if not."""
        if not entry.get("repo") or not entry.get("gt_solution") or not entry.get("code"):
            return "drop", "missing repo/gt_solution/buggy_code"
        status, val_id, _ = self._run(entry, entry["code"], sw)
        if status == "identical":
            return "correct", None
        if status == "1+_f2p":
            f2p = None
            report_path = sw["LOG_DIR"] / entry["repo"] / val_id / sw["LOG_REPORT"]
            if report_path.exists():
                try:
                    report = json.loads(report_path.read_text())
                    f2p = {"FAIL_TO_PASS": report.get("FAIL_TO_PASS", []),
                           "PASS_TO_PASS": report.get("PASS_TO_PASS", [])}
                except Exception:
                    pass
            return "fail", f2p
        if status == "0_f2p":
            aug_fail = self._augmented_failures(entry, entry["code"], sw)
            if aug_fail:
                return "fail", {"FAIL_TO_PASS": aug_fail, "PASS_TO_PASS": []}
            return "correct", None
        return "drop", f"status={status}"

    def _judge_fix(self, entry: dict, sw: dict):
        """fix-eval: ("correct", None) iff no clean-passing test breaks."""
        code = entry.get("code") or ""
        if not entry.get("repo") or not entry.get("gt_solution") or not code.strip():
            return "fail", "missing gt_solution/solution/repo"
        if _syntax_ok(entry["gt_solution"]) and not _syntax_ok(code):
            return "fail", "solution is not valid Python"
        status, val_id, _ = self._run(entry, code, sw)
        if status == "identical":
            return "correct", None
        if status != "0_f2p":
            return "fail", f"status={status}"
        broken = self._broken_tests(entry["repo"], val_id, sw)
        if broken is None:
            return "fail", "missing test logs"
        if broken:
            return "fail", f"{len(broken)} tests no longer pass: {broken[:5]}"
        aug_fail = self._augmented_failures(entry, code, sw)
        if aug_fail:
            return "fail", f"{len(aug_fail)} augmented tests fail: {aug_fail[:5]}"
        return "correct", None

    # ── test-adequacy hooks (see src/test_adequacy.py) ───────────────────────

    def _container_command(self, repo: str, sw: dict, inner: str) -> str:
        """Wrap `inner` with the repo's environment activation (prefix of test_cmd)."""
        rp = sw["registry"].get(repo)
        parts = [p.strip() for p in rp.test_cmd.split(";") if p.strip()]
        prefix = [p for p in parts[:-1]]
        return "; ".join(prefix + ["cd /testbed", inner])

    def _pytest_args(self, repo: str, sw: dict) -> list[str]:
        """Arguments of the repo's pytest command (without the leading `pytest`)."""
        rp = sw["registry"].get(repo)
        cmd = [p.strip() for p in rp.test_cmd.split(";") if p.strip()][-1].split()
        if cmd[:1] == ["pytest"]:
            return cmd[1:]
        if cmd[:3] == ["python", "-m", "pytest"]:
            return cmd[3:]
        raise NotImplementedError(f"{repo}: test command is not pytest-based: {rp.test_cmd!r}")

    def _exec_in_container(self, repo: str, files: dict[str, str], command: str,
                           sw: dict, timeout: int = 3600) -> str:
        """Start the repo image, write files (paths relative to /testbed), run command."""
        import docker
        import io
        import tarfile

        rp = sw["registry"].get(repo)
        rp.arch = "x86_64"
        rp.pull_image()
        client = docker.from_env()
        container = client.containers.create(image=rp.image_name, command="tail -f /dev/null",
                                             detach=True, platform="linux/x86_64", mem_limit="10g")
        try:
            container.start()
            buf = io.BytesIO()
            with tarfile.open(fileobj=buf, mode="w") as tar:
                for rel, content in files.items():
                    data = content.encode()
                    info = tarfile.TarInfo(name=rel.lstrip("/"))
                    info.size = len(data)
                    tar.addfile(info, io.BytesIO(data))
            container.put_archive("/testbed", buf.getvalue())
            wrapped = f"timeout {timeout} bash -c {shlex.quote(command)}"
            result = container.exec_run(["bash", "-c", wrapped], workdir="/testbed")
            return result.output.decode("utf-8", errors="replace")
        finally:
            container.remove(force=True)

    def run_tests_in_container(self, repo: str, files: dict[str, str], test_ids: list[str],
                               sw: dict | None = None, extra_setup: str = "") -> dict[str, str]:
        """Run the given pytest node ids with `files` written into the repo; id -> status."""
        sw = sw or _import_swesmith()
        args = " ".join(shlex.quote(t) for t in test_ids)
        inner = f"{extra_setup + '; ' if extra_setup else ''}pytest -p no:cacheprovider -rA --tb=no -v {args}"
        out = self._exec_in_container(repo, files, self._container_command(repo, sw, inner), sw)
        return sw["registry"].get(repo).log_parser(out)

    def measure_line_coverage(self, tasks: list[dict], extra_tests: dict[str, dict] | None = None,
                              extra_setup: str = "") -> dict[str, dict]:
        """
        Run each repo's suite once under src/line_tracer.py on the clean repo.

        Returns task_id -> {"hit_lines": [...], "test_status": {...}}. Tasks whose
        repo could not be traced are omitted (callers treat them as unmeasured).

        extra_tests maps task_id -> {path: content} of augmented test files. When
        given, ONLY those files are run (with the files written into the repo), so
        callers union the result with the coverage of the original suite.
        """
        sw = _import_swesmith()
        by_repo: dict[str, list[dict]] = {}
        for t in tasks:
            by_repo.setdefault(t["repo"], []).append(t)
        tracer = _TRACER_SRC.read_text()
        out: dict[str, dict] = {}
        for repo, repo_tasks in by_repo.items():
            files = {".pdb_line_tracer.py": tracer}
            if extra_tests is None:
                try:
                    test_args = " ".join(self._pytest_args(repo, sw))
                except NotImplementedError as e:
                    print(f"[coverage] skip: {e}")
                    continue
            else:
                paths = []
                for t in repo_tasks:
                    for path, content in extra_tests.get(t["task_id"], {}).items():
                        files[path] = content
                        paths.append(path)
                if not paths:
                    continue
                test_args = "--tb=no -v " + " ".join(shlex.quote(p) for p in paths)
            targets = sorted({t["target_file"] for t in repo_tasks})
            target_args = " ".join(f"--target {shlex.quote(p)}" for p in targets)
            inner = (f"{extra_setup + '; ' if extra_setup else ''}"
                     f"python .pdb_line_tracer.py --out /tmp/pdb_cov.json {target_args} -- "
                     f"-p no:cacheprovider -rA {test_args}; "
                     f"echo '<<PDB_COV>>'; cat /tmp/pdb_cov.json")
            print(f"[coverage] tracing {len(targets)} file(s) in {repo} ...")
            try:
                log = self._exec_in_container(repo, files, self._container_command(repo, sw, inner), sw)
                test_log, _, cov_json = log.rpartition("<<PDB_COV>>")
                hits = json.loads(cov_json.strip())
            except Exception as e:
                print(f"[coverage] {repo}: tracing failed ({type(e).__name__}: {e})")
                continue
            status = sw["registry"].get(repo).log_parser(test_log)
            for t in repo_tasks:
                out[t["task_id"]] = {"hit_lines": hits.get(t["target_file"], []),
                                     "test_status": status}
        return out

    def augmented_test_path(self, task: dict, index: int = 0) -> str:
        """Repo-relative path for a generated test file of this task."""
        stem = task["target_file"].replace("/", "__").removesuffix(".py").replace(".", "_")
        return f"{AUGMENTED_TEST_DIR}/test_{stem}_{index}.py"

    def module_name(self, task: dict) -> str:
        """Importable module path of the target file (src/ layout aware)."""
        path = task["target_file"].removesuffix(".py")
        path = path.removeprefix("src/")
        return path.replace("/", ".").removesuffix(".__init__")
