"""
DatasetHandler for SWE-smith repositories (Docker-based evaluation).

Each PDB task is one Python file from a SWE-smith repository image. Programs are
validated by applying a unified-diff patch to the clean repository inside the
repo's Docker image and running the full test suite (``swesmith.harness.valid``).

Two modes share the same entry points; the mode is recorded per entry in the
verify JSONL written by ``build_verify_unit_test``:

  bug-gen  (``sol_field == "buggy_code"``): a candidate bug is valid iff it breaks
           at least one test that passes on the clean repo ("1+_f2p").
  fix-eval (any other ``sol_field``): a model fix is correct iff every test that
           passes on the clean repo still passes after the fix.

Task metadata (gt_solution, repo, target_file, ...) is looked up in an in-memory
index that is filled from the entries passed to ``save_formatted_gt`` (both the
bug-generation pipeline and the Evaluator call it before verification), and
optionally from a JSON file given at construction time.
"""
